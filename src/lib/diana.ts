function normaliseLastInitial(v: unknown, fallback: string): string {
  const s = typeof v === 'string' ? v.trim() : ''
  const letter = s.replace(/\.$/, '').charAt(0)
  return letter ? `${letter.toUpperCase()}.` : fallback
}

function clampAge(v: unknown): number {
  const n = typeof v === 'number' && Number.isFinite(v) ? Math.round(v) : DEFAULT_GENERATED_PROSPECT.age
  return Math.max(30, Math.min(58, n))
}

// Never trust the model's JSON blindly — validate shape, clamp ranges, fall back
// to sane defaults field-by-field (same principle as scoreCall's clamp() below).
function sanitiseGeneratedProspect(parsed: unknown): GeneratedProspect {
  const p = (parsed && typeof parsed === 'object' ? parsed : {}) as Record<string, unknown>
  const str = (v: unknown, fallback: string): string => (typeof v === 'string' && v.trim() ? v.trim() : fallback)

  const financialSituation = Array.isArray(p.financialSituation)
    ? p.financialSituation.filter((x): x is string => typeof x === 'string' && x.trim().length > 0).slice(0, 3)
    : []

  return {
    firstName: str(p.firstName, DEFAULT_GENERATED_PROSPECT.firstName),
    lastInitial: normaliseLastInitial(p.lastInitial, DEFAULT_GENERATED_PROSPECT.lastInitial),
    company: str(p.company, DEFAULT_GENERATED_PROSPECT.company),
    location: str(p.location, DEFAULT_GENERATED_PROSPECT.location),
    nationality: str(p.nationality, DEFAULT_GENERATED_PROSPECT.nationality),
    age: clampAge(p.age),
    occupation: str(p.occupation, DEFAULT_GENERATED_PROSPECT.occupation),
    previousLocations: str(p.previousLocations, DEFAULT_GENERATED_PROSPECT.previousLocations),
    timeInSwitzerland: str(p.timeInSwitzerland, DEFAULT_GENERATED_PROSPECT.timeInSwitzerland),
    workHistory: str(p.workHistory, DEFAULT_GENERATED_PROSPECT.workHistory),
    financialSituation: financialSituation.length > 0 ? financialSituation : DEFAULT_GENERATED_PROSPECT.financialSituation,
    personality: str(p.personality, DEFAULT_GENERATED_PROSPECT.personality),
    earlyObjection: typeof p.earlyObjection === 'string' && p.earlyObjection.trim() ? p.earlyObjection.trim() : null,
    openingLine: str(p.openingLine, DEFAULT_GENERATED_PROSPECT.openingLine),
    todayAngle: typeof p.todayAngle === 'string' && p.todayAngle.trim() ? p.todayAngle.trim() : null,
  }
}

// Single Haiku call on session start. Falls back to a fixed default prospect
// (not a thrown error) if generation returns unparseable JSON — a bad roll of
// the dice shouldn't strand the user unable to start a session at all.
//
// `recentFirstNames` counters a real failure mode observed in testing: asked to
// "pick randomly" with no actual entropy source, Haiku gravitates to the same
// handful of names (three sessions in a row all came back "Marcus"). Passing
// back what's already been used, plus a random session seed, gives it something
// concrete to vary against instead of silently converging on its own defaults.
// `todayAngle` — today's CASSANDRA news angle, if one exists (see getTodayAngle in
// tools/diana-db.ts) — nudges the generated situation to feel topical without
// forcing it. Not model-generated: we set it on the prospect deterministically
// after generation, same principle as clampAge/normaliseLastInitial above — never
// trust the model to echo back a value we already know ourselves.
export async function generateProspect(recentFirstNames: string[] = [], todayAngle: string | null = null): Promise<GeneratedProspect> {
  const seed = Math.floor(Math.random() * 1_000_000)
  const avoidLine = recentFirstNames.length > 0
    ? `\n\nDo not use these first names — they were used in recent sessions: ${recentFirstNames.join(', ')}.`
    : ''
  const angleLine = todayAngle
    ? `\n\nToday's news angle: "${todayAngle}"\n\nThe prospect's situation should naturally connect to this angle.\nFor example if the angle is about Novartis job cuts — the prospect\nworks at Novartis or a similar company and feels uncertain about\ntheir future. If the angle is about UK pension IHT changes — the\nprospect has a UK pension they haven't reviewed.\n\nDon't make it obvious. Just make their situation relevant.`
    : ''
  const userText = `Generate the prospect now. (session seed: ${seed})${avoidLine}${angleLine}`

  const raw = await askWith(PROSPECT_GENERATION_SYSTEM, userText, 500, HAIKU)
  try {
    const parsed = JSON.parse(extractJson(raw)) as Record<string, unknown>
    parsed.todayAngle = todayAngle
    return sanitiseGeneratedProspect(parsed)
  } catch (err) {
    console.error('[diana] generateProspect: unparseable JSON, using fallback prospect:', err, raw.slice(0, 300))
    return { ...DEFAULT_GENERATED_PROSPECT, todayAngle }
  }
}

// Re-hydrates the prospect stored on a session row. Returns null for old rows
// (generated_prospect is null pre-migration) or any corrupt JSON.
export function parseGeneratedProspect(json: string | null): GeneratedProspect | null {
  if (!json) return null
  try {
    return sanitiseGeneratedProspect(JSON.parse(json))
  } catch {
    return null
  }
}

